/* Hyprland look: gaps, borders, rounding, opacity, shadow, blur.
   Output is the Lua table shape used by Hyprland's hyprland.lua (hl.config). */
(function () {
  'use strict';
  const HC = window.HC;
  const { el, ui, color: C } = HC;

  /* Starting values close to Hyprland's example config. */
  HC.hyprlandDefaults = function () {
    return {
      windows: 3,
      general: { gaps_in: 4, gaps_out: 8, border_size: 2, active1: C('#33ccff', 0.93), active2: C('#00ff99', 0.93), gradient: true, angle: 45, inactive: C('#595959', 0.67), layout: 'dwindle', resize_on_border: false },
      decoration: { rounding: 6, rounding_power: 2, active_opacity: 1, inactive_opacity: 1, shadow: { enabled: true, range: 4, render_power: 3, color: C('#1a1a1a', 0.93) }, blur: { enabled: false, size: 3, passes: 1 } },
      animations: { enabled: true },
      wallpaper: C('#1b2330'),
    };
  };

  /* dwindle: each new window splits the last one along its longer side */
  function dwindle(n, x, y, w, h, gap) {
    const rects = []; let r = { x, y, w, h };
    for (let i = 0; i < n; i++) {
      if (i === n - 1) { rects.push(r); break; }
      if (r.w >= r.h) { const a = (r.w - gap) / 2; rects.push({ x: r.x, y: r.y, w: a, h: r.h }); r = { x: r.x + a + gap, y: r.y, w: r.w - a - gap, h: r.h }; }
      else { const a = (r.h - gap) / 2; rects.push({ x: r.x, y: r.y, w: r.w, h: a }); r = { x: r.x, y: r.y + a + gap, w: r.w, h: r.h - a - gap }; }
    }
    return rects;
  }
  function master(n, x, y, w, h, gap) {
    if (n === 1) return [{ x, y, w, h }];
    const mw = (w - gap) * 0.55, rects = [{ x, y, w: mw, h }];
    const sh = (h - gap * (n - 2)) / (n - 1);
    for (let i = 0; i < n - 1; i++) rects.push({ x: x + mw + gap, y: y + i * (sh + gap), w: w - mw - gap, h: sh });
    return rects;
  }

  const APPS = [
    { t: 'kitty — ~/.config/hypr', body: '<span class="p">❯</span> ls\nhypridle.conf  hyprland.lua  hyprlock.conf\n<span class="p">❯</span> hyprctl reload\n<span class="d">ok</span>\n<span class="p">❯</span> ' },
    { t: 'firefox', body: 'wiki.hypr.land\n\n▸ Configuring\n▸ Hypr Ecosystem\n▸ Useful Utilities' },
    { t: 'btop', body: 'cpu  ▁▂▃▅▇▅▃▂▁  23%\nmem  ████░░░░  7.9G\nnet  ↓ 43M  ↑ 1M' },
    { t: 'mpv', body: '\n   ▶  02:14 / 04:51\n\n   ━━━━━━━━○──────' },
    { t: 'nvtop', body: 'GPU 0   P2  1515 MHz\nload ▇▇▇▇▅▃  61%' },
  ];

  function renderDesktop(stage, st, mon) {
    const W = mon.w, H = mon.h, g = st.general, d = st.decoration;
    const screen = el('div', { class: 'desk-screen', style: `width:${W}px;height:${H}px;background:${HC.toCss(st.wallpaper)}` });
    const barH = 0;
    const area = { x: g.gaps_out, y: g.gaps_out + barH, w: W - 2 * g.gaps_out, h: H - 2 * g.gaps_out - barH };
    const rects = (g.layout === 'master' ? master : dwindle)(st.windows, area.x, area.y, area.w, area.h, g.gaps_in * 2);
    const border = g.gradient
      ? `linear-gradient(${90 - g.angle}deg, ${HC.toCss(g.active1)}, ${HC.toCss(g.active2)})`
      : HC.toCss(g.active1);
    rects.forEach((r, i) => {
      const active = i === 0, app = APPS[i % APPS.length];
      const bs = g.border_size, rad = d.rounding;
      const win = el('div', { class: 'desk-win' + (active ? ' active' : '') });
      win.style.cssText = `left:${r.x}px;top:${r.y}px;width:${r.w}px;height:${r.h}px;border-radius:${rad + bs}px;padding:${bs}px;` +
        `background:${active ? border : HC.toCss(g.inactive)};opacity:${active ? d.active_opacity : d.inactive_opacity};` +
        (d.shadow.enabled ? `box-shadow:0 0 ${d.shadow.range * 2}px ${d.shadow.range / 2}px ${HC.toCss(d.shadow.color)};` : '');
      const inner = el('div', { class: 'desk-win-inner', style: `border-radius:${rad}px;${d.blur.enabled && (active ? d.active_opacity : d.inactive_opacity) < 1 ? `backdrop-filter:blur(${d.blur.size * d.blur.passes}px);` : ''}` });
      const pre = el('pre', { class: 'desk-app' }); pre.innerHTML = app.body; // fixed sample text, not user input
      inner.append(el('div', { class: 'desk-title' }, app.t), pre);
      win.append(inner); screen.append(win);
    });
    stage.replaceChildren(screen);
  }

  const lua = (v) => (typeof v === 'string' ? JSON.stringify(v) : String(v));
  function emit(st) {
    const g = st.general, d = st.decoration;
    const active = g.gradient
      ? `{ colors = {${lua(HC.toHypr(g.active1))}, ${lua(HC.toHypr(g.active2))}}, angle = ${g.angle} }`
      : lua(HC.toHypr(g.active1));
    return `-- Look section for hyprland.lua, generated by hypr-generator.
-- Merge these keys into your existing hl.config({ ... }) call.
hl.config({
    general = {
        gaps_in  = ${g.gaps_in},
        gaps_out = ${g.gaps_out},
        border_size = ${g.border_size},
        col = {
            active_border   = ${active},
            inactive_border = ${lua(HC.toHypr(g.inactive))},
        },
        resize_on_border = ${g.resize_on_border},
        layout = ${lua(g.layout)},
    },
    decoration = {
        rounding       = ${d.rounding},
        rounding_power = ${d.rounding_power},
        active_opacity   = ${d.active_opacity},
        inactive_opacity = ${d.inactive_opacity},
        shadow = {
            enabled      = ${d.shadow.enabled},
            range        = ${d.shadow.range},
            render_power = ${d.shadow.render_power},
            color        = ${HC.toHexInt(d.shadow.color)},
        },
        blur = {
            enabled = ${d.blur.enabled},
            size    = ${d.blur.size},
            passes  = ${d.blur.passes},
        },
    },
    animations = {
        enabled = ${st.animations.enabled},
    },
})
`;
  }

  HC.tabs.push({
    id: 'hyprland', title: 'Hyprland', file: 'look.lua', path: 'merge into ~/.config/hypr/hyprland.lua', blurb: 'Gaps, borders, rounding',
    mount(ctx) {
      const st = ctx.state.hyprland;
      const redraw = () => { renderDesktop(ctx.stage.inner, st, ctx.monitor()); ctx.fit(); ctx.output(emit(st)); ctx.save(); };
      const g = st.general, d = st.decoration;
      const draw = () => ctx.side.replaceChildren(
        ui.section('Layout',
          ui.grid(ui.select(g, 'layout', 'Layout', [['dwindle', 'dwindle'], ['master', 'master']], { onChange: redraw }), ui.number(st, 'windows', 'Sample windows', { min: 1, max: 5, onChange: redraw })),
          ui.range(g, 'gaps_in', 'Gaps between windows', { min: 0, max: 40, step: 1, onChange: redraw, fmt: (v) => `${v}px` }),
          ui.range(g, 'gaps_out', 'Gaps at screen edges', { min: 0, max: 80, step: 1, onChange: redraw, fmt: (v) => `${v}px` })),
        ui.section('Borders',
          ui.range(g, 'border_size', 'Border width', { min: 0, max: 10, step: 1, onChange: redraw, fmt: (v) => `${v}px` }),
          ui.color(g, 'active1', 'Focused border', { onChange: redraw }),
          ui.check(g, 'gradient', 'Gradient', { onChange: () => { draw(); redraw(); } }),
          g.gradient ? ui.color(g, 'active2', 'Gradient end', { onChange: redraw }) : null,
          g.gradient ? ui.range(g, 'angle', 'Gradient angle', { min: 0, max: 360, step: 5, onChange: redraw, fmt: (v) => `${v}°` }) : null,
          ui.color(g, 'inactive', 'Unfocused border', { onChange: redraw }),
          ui.check(g, 'resize_on_border', 'Resize by dragging borders', { onChange: redraw })),
        ui.section('Decoration',
          ui.range(d, 'rounding', 'Corner rounding', { min: 0, max: 30, step: 1, onChange: redraw, fmt: (v) => `${v}px` }),
          ui.range(d, 'active_opacity', 'Focused opacity', { min: 0.3, max: 1, step: 0.01, onChange: redraw }),
          ui.range(d, 'inactive_opacity', 'Unfocused opacity', { min: 0.3, max: 1, step: 0.01, onChange: redraw }),
          ui.check(d.shadow, 'enabled', 'Shadow', { onChange: redraw }),
          ui.range(d.shadow, 'range', 'Shadow size', { min: 0, max: 40, step: 1, onChange: redraw }),
          ui.color(d.shadow, 'color', 'Shadow color', { onChange: redraw }),
          ui.check(d.blur, 'enabled', 'Blur behind see-through windows', { onChange: redraw }),
          ui.grid(ui.number(d.blur, 'size', 'Blur size', { min: 1, max: 20, onChange: redraw }), ui.number(d.blur, 'passes', 'Blur passes', { min: 1, max: 6, onChange: redraw }))),
        ui.section('Preview only', ui.color(st, 'wallpaper', 'Wallpaper color', { onChange: redraw, alpha: false }),
          ui.check(st.animations, 'enabled', 'Animations (not previewed)', { onChange: redraw })));
      ctx.toolbar.replaceChildren(el('span', { class: 'sim-label' }, 'Left window is focused'));
      draw(); redraw();
    },
    unmount() {},
  });
})();
