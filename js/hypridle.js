/* hypridle designer: listeners on a timeline, split by power source. */
(function () {
  'use strict';
  const HC = window.HC;
  const { el, ui } = HC;

  const AC = 'grep -qx 1 /sys/class/power_supply/AC/online';
  const BAT = 'grep -qx 0 /sys/class/power_supply/AC/online';
  const DPMS_OFF = `hyprctl dispatch 'hl.dsp.dpms({ action = "disable" })'`;
  const DPMS_ON = `hyprctl dispatch 'hl.dsp.dpms({ action = "enable" })'`;

  /* A typical laptop setup to start from. */
  HC.hypridleDefaults = function () {
    return {
      general: { lock_cmd: 'pidof hyprlock || hyprlock', unlock_cmd: '', before_sleep_cmd: 'loginctl lock-session', after_sleep_cmd: DPMS_ON, ignore_dbus_inhibit: false },
      listeners: [
        { id: HC.uid(), comment: 'On battery, dim the screen after five idle minutes.', timeout: 300, power: 'battery', condition_cmd: '', condition_retry: 30, on_timeout: 'brightnessctl -s set 10', on_resume: 'brightnessctl -r' },
        { id: HC.uid(), comment: 'Lock after ten idle minutes.', timeout: 600, power: 'always', condition_cmd: '', condition_retry: 30, on_timeout: 'loginctl lock-session', on_resume: '' },
        { id: HC.uid(), comment: 'Turn the display off thirty seconds after locking.', timeout: 630, power: 'always', condition_cmd: '', condition_retry: 30, on_timeout: DPMS_OFF, on_resume: DPMS_ON },
        { id: HC.uid(), comment: 'On battery, suspend after thirty idle minutes.', timeout: 1800, power: 'battery', condition_cmd: '', condition_retry: 30, on_timeout: 'systemctl suspend', on_resume: '' },
      ],
    };
  };

  const POWER = [['always', 'Always'], ['ac', 'On AC power'], ['battery', 'On battery'], ['custom', 'Custom condition']];
  const condFor = (l) => (l.power === 'ac' ? AC : l.power === 'battery' ? BAT : l.power === 'custom' ? l.condition_cmd : '');

  const ACTIONS = [
    ['', 'Pick an action…'],
    [DPMS_OFF, 'Screen off'],
    ['loginctl lock-session', 'Lock (via loginctl)'],
    ['pidof hyprlock || hyprlock', 'Lock (hyprlock)'],
    ['systemctl suspend', 'Suspend'],
    ['systemctl suspend-then-hibernate', 'Suspend, then hibernate'],
    ['brightnessctl -s set 10', 'Dim to 10%'],
  ];

  const describe = (cmd) => {
    if (!cmd) return '';
    const hit = ACTIONS.find(([v]) => v && v === cmd);
    if (hit) return hit[1];
    if (/dpms.*disable|dpms off/.test(cmd)) return 'Screen off';
    if (/hyprlock|lock-session/.test(cmd)) return 'Lock';
    if (/suspend-then-hibernate/.test(cmd)) return 'Suspend → hibernate';
    if (/suspend/.test(cmd)) return 'Suspend';
    if (/hibernate/.test(cmd)) return 'Hibernate';
    if (/dim|brightness/.test(cmd)) return 'Dim';
    return cmd.split('/').pop().slice(0, 28);
  };
  const fmtT = (s) => (s % 60 === 0 ? `${s / 60} min` : s > 60 ? `${Math.floor(s / 60)} min ${s % 60} s` : `${s} s`);

  function renderTimeline(stage, st) {
    const max = Math.max(600, ...st.listeners.map((l) => +l.timeout || 0)) * 1.12;
    const lanes = [['ac', 'On AC power'], ['battery', 'On battery']];
    const wrap = el('div', { class: 'idle-timeline' });
    const ticks = el('div', { class: 'idle-ticks' });
    const step = max > 3600 ? 900 : max > 1500 ? 300 : 60;
    for (let t = 0; t <= max; t += step) ticks.append(el('span', { style: `left:${(t / max) * 100}%` }, t === 0 ? 'idle' : fmtT(t)));
    wrap.append(ticks);
    for (const [k, name] of lanes) {
      const lane = el('div', { class: 'idle-lane' }, el('div', { class: 'idle-lane-name' }, name));
      const track = el('div', { class: 'idle-track' });
      const hits = st.listeners.filter((l) => l.power === 'always' || l.power === k || l.power === 'custom').sort((a, b) => a.timeout - b.timeout);
      hits.forEach((l, i) => {
        track.append(el('div', { class: 'idle-event' + (l.power === 'custom' ? ' maybe' : '') + (l.timeout / max > 0.6 ? ' late' : ''), style: `left:${(l.timeout / max) * 100}%;--row:${i % 3}`, title: l.comment },
          el('span', { class: 'idle-pin' }), el('span', { class: 'idle-tag' }, `${fmtT(l.timeout)} · ${describe(l.on_timeout) || 'nothing'}`)));
      });
      lane.append(track); wrap.append(lane);
    }
    const legend = el('p', { class: 'hint idle-legend' }, 'Each listener fires once per idle period. Any input resets the clock and runs every fired listener\'s on-resume command. A dashed marker depends on a custom condition.');
    stage.replaceChildren(el('div', { class: 'idle-stage' }, el('h2', { class: 'stage-title' }, 'What happens while you are away'), wrap, legend));
  }

  const q = (s) => String(s).replace(/#/g, '##');
  function emit(st) {
    const o = ['# hypridle.conf, generated by hypr-generator', '', 'general {'];
    for (const [k, v] of Object.entries(st.general)) { if (v === '' || v === false) continue; o.push(`    ${k} = ${typeof v === 'string' ? q(v) : v}`); }
    o.push('}');
    for (const l of [...st.listeners].sort((a, b) => a.timeout - b.timeout)) {
      o.push('');
      if (l.comment) o.push(`# ${l.comment}`);
      o.push('listener {', `    timeout = ${l.timeout}`);
      const cond = condFor(l);
      if (cond) o.push(`    condition_cmd = ${q(cond)}`, `    condition_retry = ${l.condition_retry}`);
      if (l.on_timeout) o.push(`    on-timeout = ${q(l.on_timeout)}`);
      if (l.on_resume) o.push(`    on-resume = ${q(l.on_resume)}`);
      o.push('}');
    }
    return o.join('\n') + '\n';
  }

  function listenerEditor(st, l, changed) {
    const c = () => changed(false);
    const quick = el('select', { 'aria-label': 'Quick action' }, ACTIONS.map(([v, t]) => el('option', { value: v }, t)));
    quick.addEventListener('change', () => {
      if (!quick.value) return;
      l.on_timeout = quick.value;
      l.on_resume = quick.value === DPMS_OFF ? DPMS_ON : /brightnessctl -s/.test(quick.value) ? 'brightnessctl -r' : '';
      changed(true);
    });
    return el('div', { class: 'widget-body' },
      ui.text(l, 'comment', 'Note', { onChange: c, mono: false }),
      ui.grid(ui.number(l, 'timeout', 'After (seconds idle)', { min: 1, onChange: c }), ui.select(l, 'power', 'When', POWER, { onChange: () => changed(true) })),
      l.power === 'custom' ? ui.text(l, 'condition_cmd', 'Condition command (exit 0 = run)', { onChange: c }) : null,
      el('div', { class: 'field' }, el('label', {}, 'Quick action'), quick),
      ui.text(l, 'on_timeout', 'On timeout', { onChange: c }),
      ui.text(l, 'on_resume', 'On resume', { onChange: c }));
  }

  HC.tabs.push({
    id: 'hypridle', title: 'hypridle', file: 'hypridle.conf', path: '~/.config/hypr/hypridle.conf', blurb: 'Idle actions',
    mount(ctx) {
      const st = ctx.state.hypridle;
      const redraw = () => { renderTimeline(ctx.stage.inner, st); ctx.fit(true); ctx.output(emit(st)); ctx.save(); };
      const draw = () => {
        const list = el('div', { class: 'widget-list' });
        [...st.listeners].sort((a, b) => a.timeout - b.timeout).forEach((l) => {
          const det = el('details', { class: 'widget' });
          det.append(el('summary', {}, el('span', { class: 'wtype' }, fmtT(l.timeout)), el('span', { class: 'wname' }, l.comment || describe(l.on_timeout)),
            el('button', { type: 'button', class: 'icon-btn', 'aria-label': `Remove ${l.comment || 'listener'}`, onclick: (e) => { e.preventDefault(); st.listeners = st.listeners.filter((x) => x !== l); draw(); redraw(); } }, '×')));
          det.addEventListener('toggle', () => { if (det.open && !det.querySelector('.widget-body')) det.append(listenerEditor(st, l, (structural) => { if (structural) { draw(); } redraw(); })); });
          list.append(det);
        });
        list.append(el('div', { class: 'row-btns' }, el('button', { type: 'button', class: 'btn', onclick: () => { st.listeners.push({ id: HC.uid(), comment: 'New listener', timeout: 600, power: 'always', condition_cmd: '', condition_retry: 30, on_timeout: '', on_resume: '' }); draw(); redraw(); } }, 'Add listener')));
        ctx.side.replaceChildren(
          ui.section('Listeners', el('p', { class: 'hint' }, 'Starts from a typical laptop setup. Battery and AC conditions check /sys/class/power_supply/AC/online; your adapter may be named differently (ls /sys/class/power_supply).'), list),
          ui.section('General',
            ui.text(st.general, 'lock_cmd', 'lock_cmd (loginctl lock-session runs this)', { onChange: redraw }),
            ui.text(st.general, 'unlock_cmd', 'unlock_cmd', { onChange: redraw }),
            ui.text(st.general, 'before_sleep_cmd', 'before_sleep_cmd', { onChange: redraw, placeholder: 'loginctl lock-session' }),
            ui.text(st.general, 'after_sleep_cmd', 'after_sleep_cmd', { onChange: redraw }),
            ui.check(st.general, 'ignore_dbus_inhibit', 'Ignore apps that block idle (video players, browsers)', { onChange: redraw })));
      };
      ctx.toolbar.replaceChildren(el('span', { class: 'sim-label' }, 'Timeline of one idle period'));
      draw(); redraw();
    },
    unmount() {},
  });
})();
